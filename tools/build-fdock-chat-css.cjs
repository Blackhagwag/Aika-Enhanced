// Builds vendor/steam-enhanced/client/friends/friends-dock-aika.css: Aika's own look of Steam's
// chat (sections/friends.css, part 2 "The chat window", written for the chat window,
// html.friendsui-container) rescoped to the Friends Dock's chat — Steam's Friends & Chat tree
// mounted in the dock (.se-fd-steam) and its popup over Store and Community pages
// (.se-fd-popup-host). So the built-in chat is drawn exactly as Aika draws Steam's chat window.
//   node tools/build-fdock-chat-css.cjs        (run again after sections/friends.css changes)
"use strict";
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const src = fs.readFileSync(path.join(root, "sections/friends.css"), "utf8");
const start = src.indexOf("2. The chat window");
if (start < 0) throw new Error("sections/friends.css: part 2 not found");
const from = src.lastIndexOf("/* ====", start);
const body = src.slice(from).replace(/html\.friendsui-container(?:\.ChatPopup)?/g, "html :is(.se-fd-steam, .se-fd-popup-host)");
const out = `/*
 * GENERATED by tools/build-fdock-chat-css.cjs from sections/friends.css — do not edit here.
 *
 * Aika's look of Steam's chat window, rescoped to the Friends Dock's built-in chat (Steam's own
 * Friends & Chat tree in the dock, .se-fd-steam, and its popup over browser pages,
 * .se-fd-popup-host). Listed after friends-dock-chat*.css (Steam Enhanced's flyout frame) in
 * vendor/steam-enhanced/client/loader.js.
 */

${body}`;
fs.writeFileSync(path.join(root, "vendor/steam-enhanced/client/friends/friends-dock-aika.css"), out);
console.log("friends-dock-aika.css:", out.length, "bytes,", (body.match(/:is\(\.se-fd-steam/g) || []).length, "rules rescoped");
